#!/usr/bin/env python3
"""Run every extractor against every fixture and write results/results.csv + results/results.md.

Usage:
    python scripts/run_benchmark.py
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from tebench.extractors import EXTRACTORS  # noqa: E402
from tebench.metrics import score_extraction  # noqa: E402

PDF_DIR = ROOT / "pdfs"
GT_DIR = ROOT / "ground_truth"
RESULTS_DIR = ROOT / "results"
RESULTS_DIR.mkdir(exist_ok=True)


def load_cases():
    cases = []
    for gt_path in sorted(GT_DIR.glob("*.json")):
        gt = json.loads(gt_path.read_text(encoding="utf-8"))
        pdf_path = PDF_DIR / f"{gt['id']}.pdf"
        assert pdf_path.exists(), f"missing PDF for {gt['id']}"
        cases.append((gt["id"], pdf_path, gt))
    return cases


def run():
    cases = load_cases()
    rows = []
    for case_id, pdf_path, gt in cases:
        for tool_name, fn in EXTRACTORS.items():
            t0 = time.perf_counter()
            try:
                tables = fn(pdf_path)
                error = ""
            except Exception as e:  # belt-and-braces; extractors already catch internally
                tables, error = [], f"{type(e).__name__}: {e}"
            elapsed = time.perf_counter() - t0

            metrics = score_extraction(tables, gt["rows"])
            row = {
                "case": case_id,
                "tool": tool_name,
                "runtime_sec": round(elapsed, 3),
                "error": error,
                **metrics,
            }
            rows.append(row)
            print(f"{case_id:28s} {tool_name:18s} "
                  f"recall={metrics['cell_recall']:.2f} "
                  f"accuracy={metrics['value_accuracy']:.2f} "
                  f"structure={metrics['structure_score']:.2f} "
                  f"time={elapsed:.2f}s"
                  f"{'  ERROR: ' + error if error else ''}")

    write_csv(rows)
    write_md(rows)
    print(f"\nwrote {RESULTS_DIR / 'results.csv'} and {RESULTS_DIR / 'results.md'}")


def write_csv(rows):
    import csv

    fieldnames = list(rows[0].keys())
    with open(RESULTS_DIR / "results.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(rows)


def write_md(rows):
    tools = list(EXTRACTORS.keys())
    cases = sorted({r["case"] for r in rows})
    lines = ["# Benchmark results", "", "Auto-generated by `scripts/run_benchmark.py`. Do not edit by hand.", ""]

    for metric in ["cell_recall", "value_accuracy", "structure_score"]:
        lines.append(f"## {metric}")
        lines.append("")
        header = "| case | " + " | ".join(tools) + " |"
        sep = "|---" * (len(tools) + 1) + "|"
        lines.append(header)
        lines.append(sep)
        by_case_tool = {(r["case"], r["tool"]): r for r in rows}
        for case in cases:
            cells = []
            for tool in tools:
                r = by_case_tool.get((case, tool))
                if r is None:
                    cells.append("-")
                elif r["error"]:
                    cells.append("ERROR")
                else:
                    cells.append(f"{r[metric]:.2f}")
            lines.append(f"| {case} | " + " | ".join(cells) + " |")
        lines.append("")

    lines.append("## runtime_sec")
    lines.append("")
    header = "| case | " + " | ".join(tools) + " |"
    sep = "|---" * (len(tools) + 1) + "|"
    lines.append(header)
    lines.append(sep)
    by_case_tool = {(r["case"], r["tool"]): r for r in rows}
    for case in cases:
        cells = []
        for tool in tools:
            r = by_case_tool.get((case, tool))
            cells.append(f"{r['runtime_sec']:.2f}" if r else "-")
        lines.append(f"| {case} | " + " | ".join(cells) + " |")
    lines.append("")

    (RESULTS_DIR / "results.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    run()
